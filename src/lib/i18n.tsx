const DICTS: Record<Lang, Dict> = { en, lt, ru };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict; voiceLang: string };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = localStorage.getItem("lang") as Lang | null;
    if (saved && DICTS[saved]) setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("lang", l);
  };
  const voiceLang = LANGS.find((l) => l.code === lang)!.voice;
  return <I18nContext.Provider value={{ lang, setLang, t: DICTS[lang], voiceLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
